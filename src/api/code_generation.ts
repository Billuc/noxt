import type { APIEndpointEntry, HttpMethod } from "./types";

type ApiByFileMap = Map<
  string,
  {
    prefix: string;
    route: string;
    methods: Set<HttpMethod>;
  }
>;

function groupByRoute(entries: APIEndpointEntry<any, any>[]): ApiByFileMap {
  const importMap: ApiByFileMap = new Map();

  for (const entry of entries) {
    const importPrefix = entry.route.replaceAll(/[\\\/-]/g, "_");

    if (!importMap.has(entry.file.absolute)) {
      importMap.set(entry.file.absolute, {
        prefix: importPrefix,
        route: entry.route,
        methods: new Set<HttpMethod>(),
      });
    }
    importMap.get(entry.file.absolute)!.methods.add(entry.method);
  }

  return importMap;
}

function generateImportsCode(importMap: ApiByFileMap): string[] {
  const imports: string[] = [];

  for (const [fileToImport, importData] of importMap.entries()) {
    const importElements = importData.methods
      .values()
      .map((m) => `${m} as ${importData.prefix}_${m}`)
      .toArray();
    imports.push(
      `import { ${importElements.join(", ")} } from ${JSON.stringify(fileToImport)};`,
    );
  }

  return imports;
}

function generateRouterTypeCode(apiMap: ApiByFileMap): string {
  const routesData: string[] = [];

  for (const [_file, data] of apiMap.entries()) {
    const endpoints: string[] = [];
    for (const method of data.methods) {
      endpoints.push(`"${method}": ${data.prefix}_${method}`);
    }

    routesData.push(
      `"${data.route}": {
    ${endpoints.join(",\n    ")}
  }`,
    );
  }

  return `{
  ${routesData.join(",\n  ")}
}`;
}

export function generateApiUtilsCode(
  entries: APIEndpointEntry<any, any>[],
  base?: string,
): string {
  const apiMap = groupByRoute(entries);

  return `// Auto-generated by noxt
import { ApiRouter as NoxtApiRouter } from "noxt/runtime";
import { getRoutes } from "noxt/api";
${generateImportsCode(apiMap).join("\n")}

const apiRoutesData = ${generateRouterTypeCode(apiMap)} as const;
const router = new NoxtApiRouter<typeof apiRoutesData>(${JSON.stringify(base ?? "")});
const routes = getRoutes(apiRoutesData);

type ApiRouter = typeof router;

export { router, type ApiRouter, routes };
`;
}
